// OBJ convention: Y up, metres. Model axes map to OBJ as
//   OBJ X = east (model x), OBJ Y = up (model z), OBJ Z = south (model y)
// which is right-handed, so Blender's default importer shows the building
// upright with north along +Y.
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const EcoModel = require('../../site/js/model.js');
const { MATERIALS } = require('../../site/js/render.js');

const n3 = (v) => {
  const r = Math.round(v * 1000) / 1000;
  return Object.is(r, -0) ? '0' : String(r);
};

function newell(pts) {
  const n = [0, 0, 0];
  for (let i = 0; i < pts.length; i++) {
    const a = pts[i];
    const b = pts[(i + 1) % pts.length];
    n[0] += (a[1] - b[1]) * (a[2] + b[2]);
    n[1] += (a[2] - b[2]) * (a[0] + b[0]);
    n[2] += (a[0] - b[0]) * (a[1] + b[1]);
  }
  return n;
}

const toObj = (p) => [p[0], p[2], p[1]];

export function toOBJ(model, { mtl, title }) {
  const lines = [
    '# Concept-only massing geometry, metres. Not a detailed architectural BIM.',
    `# ${title}`,
    '# Generated by tools/build.mjs from the JSON source in data/. Edit the JSON, not this file.',
    '# Axes: Y up; +X east; +Z south (north is -Z). Blender default OBJ import shows it upright.',
    `# Roof option exported: ${model.meta.roof_option}. Room floor zones are omitted.`,
    '# Licence: CC BY 4.0, Eco Hamlet contributors 2026. Not engineered, not for construction.',
    `mtllib ${mtl}`,
  ];
  const groups = new Map();
  model.prims.filter((p) => p.cat !== 'room').forEach((p) => {
    const g = (p.group || p.name).replace(/[^A-Za-z0-9_-]+/g, '_');
    if (!groups.has(g)) groups.set(g, []);
    groups.get(g).push(p);
  });
  let base = 1;
  for (const [name, prims] of groups) {
    lines.push(`o ${name}`);
    let mat = null;
    prims.forEach((p) => {
      if (p.mat !== mat) { mat = p.mat; lines.push(`usemtl ${mat}`); }
      const g = EcoModel.geometry(p);
      const v = g.v.map(toObj);
      v.forEach((q) => lines.push(`v ${n3(q[0])} ${n3(q[1])} ${n3(q[2])}`));
      g.f.forEach((f) => {
        const want = toObj(f.n);
        let idx = f.i.slice();
        const nn = newell(idx.map((i) => v[i]));
        if (nn[0] * want[0] + nn[1] * want[1] + nn[2] * want[2] < 0) idx = idx.reverse();
        lines.push('f ' + idx.map((i) => i + base).join(' '));
      });
      base += v.length;
    });
  }
  return lines.join('\n') + '\n';
}

export function toMTL(model) {
  const used = [...new Set(model.prims.filter((p) => p.cat !== 'room').map((p) => p.mat))].sort();
  const out = ['# Eco Hamlet concept materials (display colours only). CC BY 4.0.'];
  used.forEach((k) => {
    const m = MATERIALS[k] || MATERIALS.fixture;
    const c = [1, 3, 5].map((i) => (parseInt(m.fill.slice(i, i + 2), 16) / 255).toFixed(3));
    out.push('', `newmtl ${k}`, `# ${m.label}`, `Kd ${c.join(' ')}`, 'Ka 0 0 0', 'Ks 0.05 0.05 0.05', `d ${m.opacity == null ? 1 : m.opacity}`, 'illum 1');
  });
  return out.join('\n') + '\n';
}

/** Parse an OBJ back into vertices and faces (used by the tests). */
export function parseOBJ(text) {
  const v = [];
  const f = [];
  const objects = [];
  for (const line of text.split('\n')) {
    if (line.startsWith('v ')) v.push(line.slice(2).trim().split(/\s+/).map(Number));
    else if (line.startsWith('f ')) f.push(line.slice(2).trim().split(/\s+/).map((s) => parseInt(s, 10)));
    else if (line.startsWith('o ')) objects.push(line.slice(2).trim());
  }
  return { v, f, objects };
}
